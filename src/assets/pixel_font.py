# -------------------------------------------------------- glyph surfaces
_WHITE = {}          # char -> 1x white SRCALPHA surface (built lazily)


def _glyph(ch):
    rows = _G.get(ch)
    if rows is None:
        rows = _G.get(ch.upper(), _G["?"])
    surf = _WHITE.get(rows)
    if surf is None:
        surf = pygame.Surface((5, GLYPH_H), pygame.SRCALPHA)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    surf.set_at((x, y), (255, 255, 255, 255))
        _WHITE[rows] = surf
    return surf


class PixelFont:
    """Duck-typed pygame Font: render(text, aa, color) + size(text)."""

    def __init__(self, scale=1, cache_limit=512):
        self.scale = scale
        self.height = GLYPH_H * scale
        self._cache = {}
        self._limit = cache_limit

    def size(self, s):
        if not s:
            return (0, self.height)
        return ((len(s) * ADV - 1) * self.scale, self.height)

    def render(self, s, antialias=True, color=(255, 255, 255),
               background=None):
        """Composed (text, color) surface; cached. Never mutate the result —
        callers needing set_alpha must copy first (see Floaters)."""
        if not s:
            return pygame.Surface((1, self.height), pygame.SRCALPHA)
        key = (s, tuple(color))
        img = self._cache.get(key)
        if img is None:
            w1 = len(s) * ADV - 1
            base = pygame.Surface((w1, GLYPH_H), pygame.SRCALPHA)
            for i, ch in enumerate(s):
                base.blit(_glyph(ch), (i * ADV, 0))
            # white glyph pixels -> color; transparent pixels untouched
            # (RGB blend ignores the alpha channel)
            base.fill(tuple(color), special_flags=pygame.BLEND_RGB_MULT)
            if self.scale != 1:
                base = pygame.transform.scale(
                    base, (w1 * self.scale, GLYPH_H * self.scale))
            if len(self._cache) >= self._limit:
                self._cache.clear()          # bounded; cheap to rebuild
            self._cache[key] = base
            img = base
        return img

